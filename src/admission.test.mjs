import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const compile=name=>ts.transpileModule(readFileSync(new URL(name,import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const url=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const modelUrl=url(compile('./model.ts'));
const {seedTrip,getPlaces,isTrip}=await import(modelUrl);
const traitsUrl=url(compile('./pacing/traits.ts'));
const {setPlaceLastEntry}=await import(url(compile('./admission.ts').replace("from './model'",`from '${modelUrl}'`).replace("from './pacing/traits'",`from '${traitsUrl}'`)));
const {withPlaceAdmission}=await import(url(compile('./placeHours.ts')));
const trip=seedTrip(),place=getPlaces(trip).kinkakuji;
assert.ok(place);
setPlaceLastEntry(trip,place,2,990,'custom-confirmed');
assert.equal(trip.customPlaces['custom-confirmed'].lastEntryMinutes[2],990);
assert.ok(trip.days.flatMap(d=>d.items).some(item=>item.placeId==='custom-confirmed'));
assert.equal(trip.days.flatMap(d=>d.items).some(item=>item.placeId===place.id),false);
assert.equal(isTrip(trip),true);
const retained=trip.days.flatMap(d=>d.items).find(item=>item.placeId==='custom-confirmed');
assert.equal(retained.walkingMeters,1000);assert.equal(retained.exposure,'outdoor');
console.log('✓ Sample admission edits create a trip-owned place and retain valid references');
const owned=trip.customPlaces['custom-confirmed'];
setPlaceLastEntry(trip,owned,3,900,'custom-unused');
assert.deepEqual(trip.customPlaces[owned.id].lastEntryMinutes,{2:990,3:900});
setPlaceLastEntry(trip,owned,2,null,'custom-unused');
assert.deepEqual(trip.customPlaces[owned.id].lastEntryMinutes,{3:900});
setPlaceLastEntry(trip,owned,3,null,'custom-unused');
assert.equal(trip.customPlaces[owned.id].lastEntryMinutes,undefined);
console.log('✓ Admission save and clear preserve other weekdays and use current trip metadata');
for(const [day,minute] of [[7,600],[2,1440],[2,-1],[2,10.5]])assert.throws(()=>setPlaceLastEntry(trip,owned,day,minute,'custom-unused'));
assert.throws(()=>setPlaceLastEntry(trip,{...owned,id:'missing'},2,600,'custom-unused'));
console.log('✓ Invalid or removed-place admission edits are rejected');
const provider={fetchedAt:123,regularHours:{periods:[],weekdayDescriptions:[]}};
const prior=withPlaceAdmission(provider,{...owned,lastEntryMinutes:{2:990}});
assert.equal(prior.lastEntryMinutes[2],990);assert.equal(provider.lastEntryMinutes,undefined);
assert.equal(withPlaceAdmission(prior,{...owned,lastEntryMinutes:{2:975}}).lastEntryMinutes[2],975);
assert.equal(withPlaceAdmission(prior,{...owned,lastEntryMinutes:undefined}).lastEntryMinutes,undefined);
assert.equal(withPlaceAdmission(prior,{...owned,lastEntryMinutes:undefined}).regularHours,provider.regularHours);
console.log('✓ Current place metadata overrides stale proposal cutoffs and clearing removes them');
console.log('4 admission action checks passed.');
